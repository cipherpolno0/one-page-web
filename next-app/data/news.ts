const validateNewsItems = (items: NewsItem[]) => {
  const seenSlugs = new Set<string>();

  for (const item of items) {
    if (!slugPattern.test(item.slug)) {
      throw new Error(`Invalid news slug: ${item.slug}`);
    }

    if (seenSlugs.has(item.slug)) {
      throw new Error(`Duplicate news slug: ${item.slug}`);
    }

    seenSlugs.add(item.slug);
  }
};

validateNewsItems(newsItems);

export const isValidNewsSlug = (slug: string) => slugPattern.test(slug);

export const getNewsBySlug = (slug: string) => (
  isValidNewsSlug(slug) ? newsItems.find((item) => item.slug === slug) : undefined
);
